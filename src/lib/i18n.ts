/** Loads the script's Noto font only when a page first needs it. */
export function loadFont(lang: LangCode) {
  const f = LANGS[lang].font;
  if (!f || typeof document === "undefined" || f === "Noto Sans Devanagari") return;
  const id = `font-${lang}`;
  if (document.getElementById(id)) return;
  const l = document.createElement("link");
  l.id = id; l.rel = "stylesheet";
  l.href = `https://fonts.googleapis.com/css2?family=${f.replace(/ /g, "+")}:wght@400;500;600&display=swap`;
  document.head.appendChild(l);
}
export const fontStyle = (lang: LangCode) => (LANGS[lang].font ? { fontFamily: `"${LANGS[lang].font}", sans-serif` } : undefined);

